const COMPANY_SIZE_OVERRIDES = Object.fromEntries(
  Object.entries(OVERRIDES_BY_BUCKET).flatMap(([bucket, names]) =>
    names.map(name => [name, Number(bucket)]),
  ),
)

export function getCompanySizeMeta(company, index = 0) {
  const base = COMPANY_SIZE_OVERRIDES[company.name] ?? SECTOR_SIZE_BASE[company.sector] ?? 3
  const bucket = Math.max(1, Math.min(5, base))
  const score = bucket * 1000 - index // ensure stable ordering within bucket
  return {
    bucket,
    label: SIZE_LABELS[bucket],
    score,
  }
}
